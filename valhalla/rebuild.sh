#!/usr/bin/env bash
# Ручная публикация кастомных дорог, без заявки в АСУ.
#
# Всю работу делает publisher: staging-копия карты -> экспорт .osc из API
# АСУ -> osmium apply-changes -> сборка тайлов одноразовым контейнером ->
# патч конфига + смоук -> swap каталогов -> перезапуск живого сервиса.
# Живой контейнер обслуживает запросы все время сборки (около часа),
# простой только на секунды перезапуска. Предыдущее поколение тайлов
# остается в <сезон>_prev для мгновенного отката.
#
# Тем же путем идет и автоматическая публикация: publisher в режиме
# worker сам забирает заявки из API. Скрипт нужен, когда заявку заводить
# не хочется - например при первичном наполнении тайлсета.
#
# Использование:
#   ./rebuild.sh [summer|winter]
set -euo pipefail

SEASON="${1:-summer}"
DIR="$(cd "$(dirname "$0")" && pwd)"

# PWD задает дефолт HOST_FILES_DIR в docker-compose.yml
cd "$DIR"

docker compose run --rm publisher \
    python -m publisher.cli publish --season "$SEASON"
